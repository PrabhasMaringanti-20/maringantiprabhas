/**
 * Regenerates src/data/posterImages.ts from whatever sits in
 * assets/images/posters/.
 *
 * Metro resolves `require` at build time, so a poster dropped into that folder
 * cannot be picked up from a runtime path — the map has to be generated. Name
 * each file after its catalogue id, e.g. `infinity-war.jpg`.
 *
 *   npm run posters
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const posterDir = join(root, 'assets/images/posters');
const outFile = join(root, 'src/data/posterImages.ts');

const movies = JSON.parse(readFileSync(join(root, 'src/data/movies.json'), 'utf8'));
const knownIds = new Set(movies.map((movie) => movie.id));

const files = readdirSync(posterDir)
  .filter((name) => /\.(jpg|jpeg|png|webp)$/i.test(name))
  .sort();

const entries = [];
const unknown = [];

for (const file of files) {
  const id = file.replace(/\.(jpg|jpeg|png|webp)$/i, '');
  if (knownIds.has(id)) entries.push([id, file]);
  else unknown.push(file);
}

const body = entries
  .map(([id, file]) => `  '${id}': require('../../assets/images/posters/${file}'),`)
  .join('\n');

writeFileSync(
  outFile,
  `import type { ImageSourcePropType } from 'react-native';

/**
 * Local movie posters, keyed by catalogue id.
 *
 * GENERATED by scripts/generate-poster-map.mjs — do not edit by hand. Drop a
 * poster named after its catalogue id into assets/images/posters/ and run
 * \`npm run posters\`.
 *
 * A TMDB key takes precedence over these; without either, the poster falls back
 * to a typographic card.
 */
export const LOCAL_POSTERS: Record<string, ImageSourcePropType> = {
${body}
};

export function localPoster(movieId: string): ImageSourcePropType | undefined {
  return LOCAL_POSTERS[movieId];
}
`,
);

console.log(`Wrote ${entries.length} poster${entries.length === 1 ? '' : 's'} to src/data/posterImages.ts`);
if (unknown.length) {
  console.warn(`Skipped (no catalogue id matches): ${unknown.join(', ')}`);
}
const missing = movies.filter((movie) => !entries.some(([id]) => id === movie.id));
if (missing.length) {
  console.log(`\n${missing.length} title${missing.length === 1 ? '' : 's'} still without a local poster:`);
  for (const movie of missing) console.log(`  ${movie.id}.jpg   (${movie.title})`);
}
